"""
scripts/seed_redis_features.py
================================
Batch Redis Materialization — v2 Feature Set

Reads the SAME parquet files used to train the current production models:
  - ml/data/processed/features_lgbm_v3.parquet     (66 LightGBM features)
  - ml/data/processed/features_autoencoder_v3.parquet  (21 AE features)

Both files were generated by ml/features/feature_engineering.py on Sep 9 2026,
which is the same run used to train ml/models/lightgbm_retrain/lgbm_best.pkl.

Strategy: for each account (from_account), take its LAST chronological row
— the most recent feature snapshot before cut-off — and HSET all features
into Redis at key: muleguard:features:account:{account_id}

The AI engine reads this key in feature_store.py:
    self._client.hgetall(f"muleguard:features:account:{txn.from_account}")

Run:
    docker compose up -d redis
    .venv\\Scripts\\python.exe scripts/seed_redis_features.py

Optional args:
    --host localhost  (default)
    --port 6379       (default)
    --ttl  1800       (seconds per key, default 30 min — 0 = no expiry)
    --batch 5000      (pipeline chunk size)
"""

from __future__ import annotations

import argparse
import logging
import time
from pathlib import Path

import pandas as pd
import pyarrow.parquet as pq

try:
    import redis
except ImportError:
    print("redis-py not installed. Run: .venv\\Scripts\\pip install redis")
    raise

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)-7s | %(message)s",
)
log = logging.getLogger("seed_redis")

# ---------------------------------------------------------------------------
# Paths — must match the files used to train lgbm_best.pkl
# ---------------------------------------------------------------------------
_ROOT = Path(__file__).resolve().parent.parent
LGBM_PARQUET  = _ROOT / "ml" / "data" / "processed" / "features_lgbm_v3.parquet"
AE_PARQUET    = _ROOT / "ml" / "data" / "processed" / "features_autoencoder_v3.parquet"
CLEAN_PARQUET = _ROOT / "ml" / "data" / "processed" / "transactions_clean.parquet"

# Features computed on-the-fly by ai-engine/feature_store.py — skip from Redis
# (these are derivable from a single transaction event, no history needed)
ON_THE_FLY_FEATURES = {
    "log_amount_paid", "log_amount_received",
    "amount_paid", "amount_received",
    "is_large_amount",
    "round_amount_flag", "structuring_threshold_flag",
    "is_ach_payment", "is_cash_payment", "is_bitcoin_transaction",
    "is_cross_currency",
    "payment_format_encoded", "payment_format_id",
    "hour_of_day", "day_of_week", "is_night", "is_night_transaction",
    "is_weekend",
    "hour_sin", "hour_cos", "weekday_sin", "weekday_cos",
    "hour_of_day_norm", "day_of_week_norm",
    "is_self_transfer",
    "amount_ratio", "amount_difference",
    # BUG FIX: day_of_month and minute_of_hour are event-level features
    # (extracted from the live transaction timestamp) and must NEVER be
    # saved to Redis. Storing them caused the inference API to evaluate
    # every transaction using the account's last-historical date instead
    # of the actual submitted transaction date.
    "day_of_month",
    "minute_of_hour",
}


def load_latest_per_account(
    lgbm_path:  Path,
    ae_path:    Path,
    clean_path: Path,
) -> pd.DataFrame:
    """
    Returns one row per account — its LAST chronological feature snapshot.
    Combines all 66 LGBM + 21 AE features, deduplicating overlapping columns.

    NOTE: features_lgbm_v3.parquet does NOT contain from_account — it was
    stripped by feature_engineering.py. We restore it from transactions_clean.parquet
    which is guaranteed to have the same row order (feature_engineering.py sorts
    both by from_account then timestamp before writing the feature parquets).
    """
    # 1. Load from_account + timestamp from the clean transactions parquet
    log.info(f"Loading from_account + timestamp from {clean_path.name} ...")
    t0 = time.monotonic()
    df_accounts = pd.read_parquet(clean_path, columns=["from_account", "timestamp"], engine="pyarrow")
    df_accounts = df_accounts.sort_values(["from_account", "timestamp"], kind="mergesort").reset_index(drop=True)
    log.info(f"  Loaded {len(df_accounts):,} rows in {time.monotonic()-t0:.1f}s")

    # 2. Load LGBM features (sorted by feature_engineering.py in same from_account+timestamp order)
    log.info("Reading LGBM parquet schema ...")
    lgbm_schema_cols = pq.ParquetFile(str(lgbm_path)).schema.names
    lgbm_feat_cols   = [c for c in lgbm_schema_cols
                        if c not in ON_THE_FLY_FEATURES
                        and c not in ("timestamp", "is_laundering", "from_account")]
    log.info(f"Loading LGBM features ({len(lgbm_feat_cols)} cols) from {lgbm_path.name} ...")
    t0 = time.monotonic()
    df_lgbm = pd.read_parquet(lgbm_path, columns=lgbm_feat_cols, engine="pyarrow")
    df_lgbm = df_lgbm.reset_index(drop=True)
    log.info(f"  Loaded {len(df_lgbm):,} rows in {time.monotonic()-t0:.1f}s")

    # 3. Load AE-only features (same row order)
    log.info("Reading AE parquet schema ...")
    ae_schema_cols = pq.ParquetFile(str(ae_path)).schema.names
    ae_feat_cols   = [c for c in ae_schema_cols
                      if c not in ON_THE_FLY_FEATURES
                      and c not in ("timestamp", "is_laundering", "from_account")
                      and c not in lgbm_feat_cols]
    log.info(f"Loading AE-only features ({len(ae_feat_cols)} cols) from {ae_path.name} ...")
    t0 = time.monotonic()
    df_ae = pd.read_parquet(ae_path, columns=ae_feat_cols, engine="pyarrow")
    df_ae = df_ae.reset_index(drop=True)
    log.info(f"  Loaded {len(df_ae):,} rows in {time.monotonic()-t0:.1f}s")

    # 4. Combine: account IDs (aligned) + LGBM features + AE features
    log.info("Merging account IDs + LGBM + AE feature frames ...")
    df = pd.concat([df_accounts, df_lgbm, df_ae], axis=1)
    del df_lgbm, df_ae, df_accounts

    # 5. Sort by time and take the LAST row per account = most recent feature state
    log.info("Taking last (most recent) row per account ...")
    t0 = time.monotonic()
    df = df.sort_values("timestamp", kind="mergesort")
    latest = df.groupby("from_account", sort=False).tail(1).copy()
    latest = latest.drop(columns=["timestamp", "is_laundering"], errors="ignore")
    latest = latest.set_index("from_account")
    log.info(f"  {len(latest):,} unique accounts ready ({time.monotonic()-t0:.1f}s)")
    log.info(f"  Features per account: {len(latest.columns)}")
    return latest


def push_to_redis(
    df:        pd.DataFrame,
    host:      str,
    port:      int,
    ttl:       int,
    batch:     int,
) -> None:
    r = redis.Redis(
        host=host, port=port, db=0,
        socket_connect_timeout=5,
        socket_timeout=10,
        decode_responses=True,
    )
    try:
        r.ping()
        log.info(f"Redis connection OK at {host}:{port}")
    except redis.exceptions.ConnectionError as exc:
        log.error("Redis is not reachable: %s", exc)
        log.error("Start Redis first:  docker compose up -d redis")
        raise

    log.info(f"Materializing {len(df):,} accounts into Redis ...")
    pipe  = r.pipeline()
    count = 0
    t0    = time.monotonic()

    for account_id, row in df.iterrows():
        key      = f"muleguard:features:account:{account_id}"
        features = {k: str(round(float(v), 8)) for k, v in row.items()
                    if pd.notna(v) and str(v) not in ("nan", "inf", "-inf")}
        if not features:
            continue
        pipe.hset(key, mapping=features)
        if ttl > 0:
            pipe.expire(key, ttl)
        count += 1
        if count % batch == 0:
            pipe.execute()
            elapsed = time.monotonic() - t0
            rate    = count / elapsed
            log.info(f"  Pushed {count:,} accounts ({rate:.0f}/s) ...")

    pipe.execute()
    elapsed = time.monotonic() - t0
    log.info(
        f"Materialization complete: {count:,} accounts pushed in {elapsed:.1f}s "
        f"({count/elapsed:.0f} accounts/s)"
    )
    if ttl > 0:
        log.info(f"TTL: each key expires in {ttl}s ({ttl//60} minutes)")
    else:
        log.info("TTL: keys never expire (ttl=0)")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Seed Redis with v2 feature snapshot")
    p.add_argument("--host",  default="localhost")
    p.add_argument("--port",  type=int, default=6379)
    p.add_argument("--ttl",   type=int, default=1800,
                   help="Key TTL in seconds (0 = no expiry). Default: 1800 (30 min)")
    p.add_argument("--batch", type=int, default=5000,
                   help="Redis pipeline chunk size. Default: 5000")
    return p.parse_args()


if __name__ == "__main__":
    args = parse_args()

    for path in (LGBM_PARQUET, AE_PARQUET, CLEAN_PARQUET):
        if not path.exists():
            raise FileNotFoundError(f"Required parquet not found: {path}")

    latest_df = load_latest_per_account(LGBM_PARQUET, AE_PARQUET, CLEAN_PARQUET)
    push_to_redis(latest_df, host=args.host, port=args.port, ttl=args.ttl, batch=args.batch)

